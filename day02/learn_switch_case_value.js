// SWITCH CASE
// Example: Identify the day of the week

function learnSwitchCase() {

    var dayOfWeek = "Tuesday";

    switch (dayOfWeek) {

        case "Monday":
            console.log("The day is Monday");
            break;

        case "Tuesday":
            console.log("The day is Tuesday");
            break;

        case "Wednesday":
            console.log("The day is Wednesday");
            break;

        case "Thursday":
            console.log("The day is Thursday");
            break;

        case "Friday":
            console.log("The day is Friday");
            break;

        case "Saturday":
            console.log("The day is Saturday");
            break;

        case "Sunday":
            console.log("The day is Sunday");
            break;

        default:
            console.log("The day is not valid");
    }
}

learnSwitchCase();