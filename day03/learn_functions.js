
// ==================================================
// JavaScript Functions - Passing Arguments
// ==================================================

// Input can be passed to a function in two ways:
//
// 1. Directly inside the function
// 2. Passing arguments to the function
//
// Passing arguments makes the test data dynamic.


// ==================================================
// Function with Parameters
// ==================================================

function login(username, password) {

    console.log(username);
    console.log(password);
}


// ==================================================
// Passing Arguments
// ==================================================

// Different values can be passed to the same function.

login("Demo1", "Pass1");
login("Demo2", "Pass2");
login("Demo3", "Pass3");
login("Demo4", "Pass4");
login("Demo5", "Pass5");

