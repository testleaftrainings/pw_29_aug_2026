
// ==================================================
// JavaScript Type Coercion
// ==================================================

// JavaScript automatically converts one data type
// into another data type when required.
// This is called Type Coercion.


// ==================================================
// Example 1: + Operator
// ==================================================

let a = "20"; // String
let b = "10"; // String

console.log(a + b);

// Output:
// "2010"
//
// When + is used with strings,
// JavaScript performs string concatenation.


// ==================================================
// Example 2: - Operator
// ==================================================

console.log(a - b);

// Output:
// 10
//
// The - operator works only with numbers.
// JavaScript converts the strings into numbers.
//
// "20" - "10"
//   20 - 10
//      = 10



