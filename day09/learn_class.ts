// Create 3 employee details.

// A class is a design or blueprint for creating objects.
// Similar to a design for a Car, we can create a design for Employee.

// The Employee class defines the properties of an employee.
class Employee {

    // Property to store the employee name.
    empName: string;

    // Property to store the employee ID.
    empID: number;
}

// An object is created from a class using the 'new' keyword.

// Create the first Employee object.
let emp1 = new Employee();

// Assign a name to the first employee.
emp1.empName = "Rahul";

// Assign an ID to the first employee.
emp1.empID = 1234;


// Create the second Employee object.
let emp2 = new Employee();

// Assign a name to the second employee.
emp2.empName = "Maha";

// Assign an ID to the second employee.
emp2.empID = 12345;


// Create the third Employee object.
let emp3 = new Employee();

// Assign a name to the third employee.
emp3.empName = "Maha";

// Assign an ID to the third employee.
emp3.empID = 12345;