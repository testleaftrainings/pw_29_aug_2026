
import { test } from "@playwright/test";

let token: any;
let id: any;

//For Basic Authentication
//const username = "admin";
//const password = "a@C2PCz3aHl/";
//const auth = Buffer.from(`${username}:${password}`).toString("base64");

test.describe.serial("Incident in ServiceNow", async () => {

  // Generate OAuth Token
  test("Test to generate token", async ({ request }) => {

    const response = await request.post("https://dev412274.service-now.com/oauth_token.do",
      {
        headers: {
          "Content-Type": "application/x-www-form-urlencoded"
        },
        form: {
          client_id: "73a82cb99bb247cf854bffddc48ffd14",
          client_secret: "Fk?gVykiCDg0p)Qp009WN[9]y<&!|wNd",
          grant_type: "password",
          username: "admin",
          password: "a@C2PCz3aHl/"
        }
      }
    );

    const responseBody = await response.json();

    console.log(responseBody);

    token = responseBody.access_token;

    console.log(token);
  });


  // Create Incident
  test("Test to create incident", async ({ request }) => {

    const response = await request.post(
      "https://dev412274.service-now.com/api/now/table/incident",
      {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
          //"Authorization": `Basic ${auth}`
        },
        data: {
          short_description: "VDI issue generated by Playwright API"
        }
      }
    );

    const responseBody = await response.json();

    console.log(responseBody);

    id = responseBody.result.sys_id;
  });


  // Retrieve Incident
  test("Test to retrieve incident", async ({ request }) => {

    const response = await request.get(
      `https://dev412274.service-now.com/api/now/table/incident/${id}`,
      {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
        }
      }
    );

    console.log(response.status());
  });


  // Update Incident
  test("Test to update incident", async ({ request }) => {

    const response = await request.put(
      `https://dev412274.service-now.com/api/now/table/incident/${id}`,
      {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
        },
        data: {
          short_description:
            "VDI issue generated by Playwright API resolved on 11-10-2026"
        }
      }
    );

    console.log(response.status());
  });


  // Delete Incident
  test("Test to delete incident", async ({ request }) => {

    const response = await request.delete(
      `https://dev412274.service-now.com/api/now/table/incident/${id}`,
      {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
        }
      }
    );

    console.log(response.status());
  });


  // Verify Deleted Incident
  test("Test to retrieve the deleted incident", async ({ request }) => {

    const response = await request.get(
      `https://dev412274.service-now.com/api/now/table/incident/${id}`,
      {
        headers: {
          "Content-Type": "application/json",
          "Authorization": `Bearer ${token}`
        }
      }
    );

    console.log(response.status());
  });

});
